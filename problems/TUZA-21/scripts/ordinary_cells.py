"""Targeted H-D component-peeling controls; exact integer recurrences, no solver."""
from itertools import combinations
from functools import lru_cache
from pathlib import Path
import json,time,datetime
W=Path(__file__).resolve().parents[1]
start=time.monotonic(); deadline=start+90

def edges(*cells):
 return set(tuple(sorted(e)) for c in cells for e in combinations(c,2))

def analyze(name,E):
 E=sorted(E); V=sorted({v for e in E for v in e}); em={e:i for i,e in enumerate(E)}
 T=[t for t in combinations(V,3) if all(tuple(e) in em for e in combinations(t,2))]
 masks=[sum(1<<em[e] for e in combinations(t,2)) for t in T]
 inc=[sum(1<<i for i,m in enumerate(masks) if m>>e&1) for e in range(len(E))]
 conflict=[sum(1<<j for j,n in enumerate(masks) if m&n) for m in masks]
 @lru_cache(None)
 def nu(s):
  if time.monotonic()>deadline:raise TimeoutError
  if not s:return 0
  i=max((i for i in range(len(T)) if s>>i&1),key=lambda i:(conflict[i]&s).bit_count())
  return max(nu(s&~(1<<i)),1+nu(s&~conflict[i]))
 @lru_cache(None)
 def tau(s):
  if time.monotonic()>deadline:raise TimeoutError
  if not s:return 0
  i=(s&-s).bit_length()-1
  return 1+min(tau(s&~inc[e]) for e in range(len(E)) if masks[i]>>e&1)
 full=(1<<len(T))-1;k=nu(full); t=tau(full)
 residual=[]
 for i in range(len(T)):
  s=full&~conflict[i]; residual.append({'triangle':T[i],'nu':nu(s),'tau':tau(s)})
 unseen=set(range(len(T))); components=[]
 while unseen:
  todo=[unseen.pop()];c=[]
  while todo:
   i=todo.pop();c.append(i);js={j for j in unseen if masks[i]&masks[j]};unseen-=js;todo.extend(js)
  components.append({'triangles':[T[i] for i in c],'nu':nu(sum(1<<i for i in c))})
 hd=bool(T) and all(r['nu']==k-1 and r['tau']==2*k-2 for r in residual)
 return {'name':name,'edges':E,'triangles':T,'nu':k,'tau':t,'residuals':residual,'hd_premise':hd,'components':components,'a1_holds_if_applicable':not hd or any(c['nu']==1 for c in components),'nu_states':nu.cache_info().currsize,'tau_states':tau.cache_info().currsize}

families=[]
for overlap in range(4):
 families.append((f'two_K4_overlap_{overlap}',edges(range(4),list(range(overlap))+list(range(4,8-overlap)))))
families += [('K4',edges(range(4))),('K5',edges(range(5))),('K6',edges(range(6)))]
for n in [3,4]:
 cells=[(i,(i+1)%n,n+2*i,n+2*i+1) for i in range(n)]
 families.append((f'cyclic_vertex_K4_cells_{n}',edges(*cells)))
 cells=[(0,1,2+2*i,3+2*i) for i in range(n)]
 families.append((f'common_edge_K4_cells_{n}',edges(*cells)))
U=(0,1,2,3);A=(1,4,6,7);B=(2,5,8,9);T=(0,4,5)
families += [('two_distinct_attachments_external_K4s',edges(U,A,B,T)),('two_distinct_attachments_without_external',edges(U,T)|{(1,4),(2,5)}),('same_attachment_without_external',edges(U,T)|{(1,4),(1,5)})]
E=edges(range(4))
for i in range(4):E|={tuple(sorted((4+i,j))) for j in ((i-1)%4,i,(i+1)%4)}
families.append(('switched_four_cycle',E))
# A path of three K4 cells sharing only vertices, with each possible single
# cross-edge between private vertices of the endpoint cells. All actual triangles
# are reconstructed, including crossing triangles generated by these joins.
base=edges((0,1,2,3),(3,4,5,6),(6,7,8,9))
for a in (0,1,2):
 for b in (7,8,9):families.append((f'K4_path_cross_edge_{a}_{b}',base|{(a,b)}))
results=[]
for name,E in families:
 try:results.append(analyze(name,E))
 except TimeoutError:results.append({'name':name,'edges':sorted(E),'status':'UNKNOWN_TIMEOUT'});break
out={'description':'Targeted cell-interface controls, not an atlas or coverage claim','utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'deadline_seconds':90,'elapsed_seconds':time.monotonic()-start,'cases':results,'complete':len(results)==len(families)}
(W/'data/ordinary_cell_controls.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps({'cases':len(results),'complete':out['complete'],'elapsed_seconds':out['elapsed_seconds'],'summary':[{k:c.get(k) for k in ['name','nu','tau','hd_premise','a1_holds_if_applicable','status']} for c in results]},indent=2))
