"""Independent AHU regeneration of the bounded triangular-unicyclic link domain.
No imports from the producer. Rooted forests are generated by unordered multisets.
The mathematical n<=9 reduction is a separate proof obligation.
"""
from functools import lru_cache
from itertools import combinations, combinations_with_replacement
from pathlib import Path
import json,hashlib

ROOTED={1:['()']}
for n in range(2,8):
 pool=sorted((k,c) for k in range(1,n) for c in ROOTED[k])
 found=[]
 def extend(left,start,children):
  if left==0:found.append('('+''.join(sorted(children))+')');return
  for i in range(start,len(pool)):
   k,c=pool[i]
   if k<=left:extend(left-k,i,children+[c])
 extend(n-1,0,[])
 ROOTED[n]=sorted(set(found))

def build(codes):
 edges=set();counter=0;roots=[]
 def parse(code,pos):
  nonlocal counter
  u=counter;counter+=1;pos+=1
  while code[pos]=='(':
   v,pos=parse(code,pos);edges.add(tuple(sorted((u,v))))
  return u,pos+1
 for code in codes:
  root,end=parse(code,0);assert end==len(code);roots.append(root)
 for e in combinations(roots,2):edges.add(tuple(sorted(e)))
 return counter,edges,roots

def match_number(n,E):
 adj=[0]*n
 for a,b in E:adj[a]|=1<<b;adj[b]|=1<<a
 @lru_cache(None)
 def rec(mask):
  if not mask:return 0
  bit=mask&-mask;v=bit.bit_length()-1;rest=mask^bit
  ans=rec(rest);nei=adj[v]&rest
  while nei:
   b=nei&-nei;nei^=b;ans=max(ans,1+rec(rest^b))
  return ans
 return rec((1<<n)-1)

pool=sorted((k,c) for k in ROOTED for c in ROOTED[k])
forests=[];links=[]
for items in combinations_with_replacement(pool,3):
 n=sum(x[0] for x in items)
 if n>9 or n<=3:continue
 codes=tuple(x[1] for x in items);n,E,roots=build(codes)
 deg=[0]*n;neigh=[set() for _ in range(n)]
 for a,b in E:deg[a]+=1;deg[b]+=1;neigh[a].add(b);neigh[b].add(a)
 leaves=[i for i in range(n) if deg[i]==1]
 parents=[next(iter(neigh[i])) for i in leaves]
 if len(set(parents))<len(parents):continue
 r=match_number(n,E)
 if r>3 or 2*r==n:continue
 fid=len(forests);forests.append({'id':fid,'n':n,'rooted_codes':codes,'cycle':roots,'edges':sorted(E),'matching_number':r,'deficiency':n-2*r,'leaves':leaves})
 mandatory=sum(1<<i for i in leaves)
 for mask in range(1<<n):
  if mask&mandatory!=mandatory or mask.bit_count()<2:continue
  LE=E|{(i,n) for i in range(n) if mask>>i&1}
  # Every nonleaf F vertex has degree >=2; all leaves are mandatory w-neighbors.
  links.append({'F_id':fid,'n':n+1,'w':n,'apex_mask':mask,'edges':sorted(LE)})
result={'scope':'All triangular-unicyclic F of order4..9, nonperfect, matching<=3, at mostone original leaf per parent; all apex neighborhoods containing leaves and size>=2','rooted_tree_counts':{k:len(v) for k,v in ROOTED.items()},'F_count':len(forests),'link_count_before_isomorphism':len(links),'F_shapes':forests,'links':links}
Path('evidence/coordinator_triangular_unicyclic_domain.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps({'F_count':len(forests),'link_count':len(links),'orders':{n:sum(f['n']==n for f in forests) for n in range(4,10)},'rooted_tree_counts':result['rooted_tree_counts']}))
